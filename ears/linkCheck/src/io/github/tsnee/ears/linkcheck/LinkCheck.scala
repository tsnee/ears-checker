package io.github.tsnee.ears.linkcheck

import scala.meta.internal.semanticdb.*
import scala.meta.internal.semanticdb.Scala.*

import zio.NonEmptyChunk

/** A public operation of the library, and the Scala expression that references it. */
final case class Operation(symbol: String, reference: String) derives CanEqual

/** Why there's no program to link: an operation the generator can't reference yet, or none. */
enum Problem derives CanEqual:
  case Overloaded(operation: String)
  case ContextParameters(operation: String)
  case Varargs(operation: String)
  case NoOperations

object Problem:

  extension (problem: Problem)

    def message: String = problem match
      case Overloaded(operation) =>
        s"$operation is overloaded; the link-check generator can't reference one overload yet"
      case ContextParameters(operation) =>
        s"$operation takes using or implicit parameters; the link-check generator can't " +
          "reference it yet"
      case Varargs(operation) =>
        s"$operation takes a variable number of arguments; the link-check generator can't " +
          "reference it yet"
      case NoOperations =>
        "the SemanticDB has no public operations; is it the library's?"

/** How an operation is referenced, from its signature. */
private enum Shape derives CanEqual:
  /** A `val`, or a `def` with no parameter list: referencing it evaluates it. */
  case Value

  /** A method whose first parameter list is empty: referenced by a function that calls it. */
  case EmptyCall

  /** A method with parameters: Scala 3 turns the reference into a function value. */
  case Function

/** Every decision behind the link-check program: which symbols in the library's SemanticDB are
  * public operations, how each is referenced, and the program's text.
  */
object LinkCheck:

  /** The public operations in `documents`, sorted by symbol, or every reason the program can't
    * reference them all. An operation is a method or an inline method written in the source (it has
    * a definition occurrence, which no compiler-generated member has), not an enum case or a
    * constructor field (data runs no code), and public along with every definition enclosing it.
    */
  def operations(documents: List[TextDocument]): Either[NonEmptyChunk[Problem], List[Operation]] =
    val symbols = documents.flatMap(_.symbols).map(info => info.symbol -> info).toMap
    val defined =
      documents.flatMap(_.occurrences).filter(_.role.isDefinition).map(_.symbol).toSet
    val found =
      symbols.values.toList.filter(isOperation(symbols, defined, _)).sortBy(_.symbol)
    NonEmptyChunk.fromIterableOption(found.flatMap(problem(symbols, _))) match
      case Some(problems)        => Left(problems)
      case None if found.isEmpty => Left(NonEmptyChunk(Problem.NoOperations))
      case None                  =>
        Right(found.map(info => Operation(info.symbol, reference(symbols, info))))

  /** The program: every reference in a list built in `main`, so every referenced method is
    * reachable and the linker checks its body. It prints how many references it holds, which shows
    * only that it ran: the count is the length of the list written here.
    */
  def program(operations: List[Operation]): String =
    val references = operations.map(operation => s"    ${operation.reference}").mkString(",\n")
    s"""|// Generated by ears.linkCheck from the library's SemanticDB; scripts/check-scalajs-link
        |// links it against the published Scala.js library. Don't edit it.
        |@main def linkCheck(): Unit =
        |  val reached: List[Any] = List(
        |$references
        |  )
        |  println(s"link-check: $${reached.size} operations reachable")
        |""".stripMargin

  /** The line the program prints when it holds `count` references. */
  def summary(count: Int): String = s"link-check: $count operations reachable"

  private def isOperation(
      symbols: Map[String, SymbolInformation],
      defined: Set[String],
      info: SymbolInformation
  ): Boolean =
    defined.contains(info.symbol) && (info.kind.isMethod || info.kind.isMacro) &&
      !has(info, SymbolInformation.Property.ENUM) && !isConstructorField(symbols, info.symbol) &&
      isPublicThroughout(symbols, info.symbol)

  private def has(info: SymbolInformation, property: SymbolInformation.Property): Boolean =
    (info.properties & property.value) != 0

  /** A field whose owner's constructor has a parameter of the same name. */
  private def isConstructorField(symbols: Map[String, SymbolInformation], symbol: String) =
    symbol.desc match
      case Descriptor.Term(name) => symbols.contains(s"${symbol.owner}`<init>`().($name)")
      case _                     => false

  /** The symbol and every definition enclosing it, up to its package, are public. */
  private def isPublicThroughout(
      symbols: Map[String, SymbolInformation],
      symbol: String
  ): Boolean =
    symbol.isPackage || symbol.isRootPackage ||
      (symbols.get(symbol).exists(isPublic) && isPublicThroughout(symbols, symbol.owner))

  private def isPublic(info: SymbolInformation): Boolean = info.access match
    case _: PublicAccess => true
    case _               => false

  /** The parameter lists of a method, or none for a `val` or a `def` without one. */
  private def parameterLists(info: SymbolInformation): List[List[String]] =
    info.signature match
      case signature: MethodSignature => signature.parameterLists.toList.map(_.symlinks.toList)
      case _                          => Nil

  private def problem(
      symbols: Map[String, SymbolInformation],
      info: SymbolInformation
  ): Option[Problem] =
    // Every parameter of the method, by symbol (`…method().(name)`), whichever list it's in.
    val parameters = symbols.values.filter(_.symbol.startsWith(s"${info.symbol}(")).toList
    val overloaded = info.symbol.desc match
      case Descriptor.Method(_, disambiguator) => disambiguator != "()"
      case _                                   => false
    val contextual = parameters.exists(parameter =>
      has(parameter, SymbolInformation.Property.GIVEN) ||
        has(parameter, SymbolInformation.Property.IMPLICIT)
    )
    val repeated = parameters.exists(_.signature match
      case signature: ValueSignature =>
        signature.tpe match
          case _: RepeatedType => true
          case _               => false
      case _ => false)
    val name = displayName(info.symbol)
    if overloaded then Some(Problem.Overloaded(name))
    else if contextual then Some(Problem.ContextParameters(name))
    else Option.when(repeated)(Problem.Varargs(name))

  private def shape(info: SymbolInformation): Shape = parameterLists(info) match
    case Nil      => Shape.Value
    case Nil :: _ => Shape.EmptyCall
    case _ :: _   => Shape.Function

  /** A member of an object by its full path; a member of a class through a parameter of that class,
    * with `?` for each type parameter. Each reference is written so that it's a value of its own,
    * with no expected type from the list: a function value, or a value.
    */
  private def reference(symbols: Map[String, SymbolInformation], info: SymbolInformation): String =
    val owner = info.symbol.owner
    val member = identifier(info.symbol.desc.value)
    val call = shape(info) match
      case Shape.EmptyCall => "()"
      case _               => ""
    owner.desc match
      case Descriptor.Type(_) =>
        // The owner's information is there: an operation's owners are all known to be public.
        val arity = symbols
          .get(owner)
          .map(_.signature)
          .collect { case signature: ClassSignature => signature.typeParameters }
          .flatten
          .fold(0)(_.symlinks.size)
        val arguments = if arity == 0 then "" else List.fill(arity)("?").mkString("[", ", ", "]")
        s"((x: ${qualified(owner)}$arguments) => x.$member$call)"
      case _ =>
        shape(info) match
          case Shape.Value     => s"(${qualified(info.symbol)}: Any)"
          case Shape.EmptyCall => s"(() => ${qualified(info.symbol)}())"
          case Shape.Function  => s"(${qualified(info.symbol)}: AnyRef)"

  /** The symbol's full name: `.` after a package or an object, `#` after a class, so a class nested
    * in a class is `Outer#Inner`.
    */
  private def qualified(symbol: String): String =
    val owner = symbol.owner
    val name = identifier(symbol.desc.value)
    if owner.isRootPackage || owner.isEmptyPackage || owner.isNone then s"_root_.$name"
    else
      val separator = owner.desc match
        case Descriptor.Type(_) => "#"
        case _                  => "."
      s"${qualified(owner)}$separator$name"

  /** The name a message uses: the enclosing definitions and the member, without packages. */
  private def displayName(symbol: String): String =
    def definitions(current: String): List[String] =
      if current.isPackage || current.isRootPackage || current.isNone then Nil
      else definitions(current.owner) :+ current.desc.value
    definitions(symbol).mkString(".")

  private def identifier(name: String): String =
    if name.matches("[A-Za-z_][A-Za-z0-9_]*") && !keywords.contains(name) then name
    else s"`$name`"

  private val keywords = Set(
    "abstract",
    "case",
    "catch",
    "class",
    "def",
    "do",
    "else",
    "enum",
    "export",
    "extends",
    "false",
    "final",
    "finally",
    "for",
    "given",
    "if",
    "implicit",
    "import",
    "lazy",
    "match",
    "new",
    "null",
    "object",
    "override",
    "package",
    "private",
    "protected",
    "return",
    "sealed",
    "super",
    "then",
    "this",
    "throw",
    "trait",
    "true",
    "try",
    "type",
    "val",
    "var",
    "while",
    "with",
    "yield"
  )
